/** 文字；缺少 key 時回傳 key 本身並記錄錯誤（Playwright 測試檢查主控台沒有錯誤） */
export function t(key, params) {
  let s = M[key];
  if (s == null) {
    console.error(`缺少介面文字：${key}`);
    return key;
  }
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] == null ? m : String(params[k])));
  return s;
}

/** 是否有這個 key */
export function has(key) {
  return Object.prototype.hasOwnProperty.call(M, key);
}

/** 系統健康項目的一行文字（「檔案描述元：…」） */
export function healthItemText(item) {
  const label = has(`health.${item.id}`) ? M[`health.${item.id}`] : item.id;
  return t('health.item', { label, summary: item.summary || '' });
}

export function statusLabel(s) {
  return has(`status.${s}`) ? M[`status.${s}`] : s;
}

export function severityLabel(s) {
  return has(`severity.${s}`) ? M[`severity.${s}`] : s;
}

export function roleLabel(r) {
  return r && has(`role.${r}`) ? M[`role.${r}`] : r || '';
}

/** 權限名稱的中文（沒有對應時照原文） */
export function permissionLabel(p) {
  return has(`perm.${p}`) ? `${M[`perm.${p}`]}（${p}）` : p;
}
