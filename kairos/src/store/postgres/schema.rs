//! PostgreSQL 後端的 schema（與 SQLite schema v9 對等；`kairos/HA.md` 第 5.3、5.5 節）。
//!
//! [`SCHEMA_V9`] 是把 SQLite 的 migration v1～v9（`store/sqlite.rs` 的 `SCHEMA_V1`～`SCHEMA_V8` 與
//! `store/sqlite/remote.rs` 的 `SCHEMA_V9`）依序套用之後的**最終狀態**，直接寫成建表 SQL；PostgreSQL 沒有
//! 「從 v1 升級」的歷史。資料表、欄位、索引的名稱與欄位順序和 SQLite 完全相同，領域 store 的查詢可以逐句對照。
//!
//! 轉寫規則：
//!
//! - `INTEGER`（含 0/1 旗標）→ `BIGINT`；`REAL` → `DOUBLE PRECISION`；`BLOB` → `BYTEA`；
//!   `TEXT` → `TEXT COLLATE "C"`（位元組順序，與 SQLite 的 BINARY 相同；主鍵、唯一鍵與索引中的文字欄位
//!   因此也是 "C" 排序）。
//! - `INTEGER PRIMARY KEY`（rowid 別名，不論有沒有 `AUTOINCREMENT`）→
//!   `BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`（見 [`IDENTITY_COLUMNS`]）。
//! - `WITHOUT ROWID` 刪除。
//! - DEFAULT、CHECK、部分索引的 `WHERE` 照搬（旗標仍是整數，比較寫 `= 1`、`IS NOT NULL`，不用布林）。
//! - 外鍵照搬：Kairos 用的是 rusqlite 內附（`bundled`）的 SQLite，編譯時預設開啟外鍵檢查
//!   （`SQLITE_DEFAULT_FOREIGN_KEYS=1`），所以 SQLite 端的 `REFERENCES … ON DELETE …` 實際上有強制，
//!   PostgreSQL 端宣告相同的外鍵，行為才一致。
//!
//! 例外（無法一對一轉寫的地方）：
//!
//! - 無型別欄位：`meta.value` 為 `TEXT COLLATE "C"`（數值以文字保存）；`reports.agent_ts` 拆成
//!   `agent_ts_ms BIGINT` 與 `agent_ts_text TEXT COLLATE "C"`，放在原本 `agent_ts` 的位置（見 [`SPLIT_COLUMNS`]）。
//! - `COLLATE NOCASE`：`users.username` 與 `config_profiles.name` 的欄位是 `TEXT COLLATE "C"`，不宣告欄位層級的
//!   UNIQUE，改為唯一索引 `users_username_lower`（`lower(username)`）、`config_profiles_name_lower`
//!   （`lower(name)`）。"C" 排序下的 `lower()` 只轉換 ASCII 字母，與 NOCASE 相同；查詢比對一律 `lower()`。
//! - 欄位或資料表層級的 UNIQUE、PRIMARY KEY 所隱含的索引由 PostgreSQL 自動命名（`<資料表>_pkey`、
//!   `<資料表>_<欄位>_key`），SQLite 端是 `sqlite_autoindex_*`，程式都不以名稱引用。
//! - SQLite 的 migration 在每一版結束時寫入 `meta.schema_upgraded_by`（值是執行時的 Kairos 版本），以及
//!   `PRAGMA user_version`／`application_id`；這些不是常數，不在這段 SQL 中，由呼叫端在同一個交易寫入
//!   （`meta` 的 `schema_version`、`application`、`schema_upgraded_by`；HA.md 第 5.3 節）。
//! - 不建立 schema、不設定 `search_path`（由呼叫端處理）；不使用擴充、分區、jsonb。

